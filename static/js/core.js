window.API = {
  async request(url, options = {}) {
    const response = await fetch(url, {
      ...options,
      headers: {
        "Content-Type": "application/json",
        ...options.headers,
      },
    })

    const data = await response.json()

    if (!response.ok) {
      throw new Error(data.error || "Request failed")
    }

    return data
  },

  get(url) {
    return this.request(url)
  },

  post(url, data) {
    return this.request(url, {
      method: "POST",
      body: JSON.stringify(data),
    })
  },

  put(url, data) {
    return this.request(url, {
      method: "PUT",
      body: JSON.stringify(data),
    })
  },

  delete(url) {
    return this.request(url, {
      method: "DELETE",
    })
  },
}






window.UIDialogs = (() => {
  const ICONS = { success: '✅', error: '❌', warning: '⚠️', info: 'ℹ️', confirm: '🗑️' };
  const TITLES = {
    success: { en: 'Success', ar: 'تم بنجاح' },
    error: { en: 'Error', ar: 'خطأ' },
    warning: { en: 'Warning', ar: 'تحذير' },
    info: { en: 'Info', ar: 'معلومة' },
    confirm: { en: 'Confirm', ar: 'تأكيد' },
  };
  const BTN_OK = { en: 'OK', ar: 'حسناً' };
  const BTN_CANCEL = { en: 'Cancel', ar: 'إلغاء' };
  const BTN_DEL = { en: 'Delete', ar: 'حذف' };
  const BTN_CONFIRM = { en: 'Confirm', ar: 'تأكيد' };
  const BTN_SUBMIT = { en: 'Submit', ar: 'إرسال' };

  function getLang() {
    return (window.I18n && window.I18n.current) ? window.I18n.current
      : (localStorage.getItem('lang') || 'en');
  }

  function isRtl() { return getLang() === 'ar'; }

  // 
  function getContainer() {
    let c = document.getElementById('toast-container');
    if (!c) {
      c = document.createElement('div');
      c.id = 'toast-container';
      document.body.appendChild(c);
    }
    c.classList.toggle('rtl', isRtl());
    return c;
  }

  function toast(message, type = 'info', duration = 4000, title = '') {
    const container = getContainer();
    const lang = getLang();
    const resolvedTitle = title || (TITLES[type] ? TITLES[type][lang] || TITLES[type].en : '');

    const el = document.createElement('div');
    el.className = `ui-toast ${type}`;
    el.style.setProperty('--duration', `${duration}ms`);
    el.innerHTML = `
      <span class="toast-icon">${ICONS[type] || 'ℹ️'}</span>
      <div class="toast-body">
        ${resolvedTitle ? `<div class="toast-title">${resolvedTitle}</div>` : ''}
        <div class="toast-message">${message}</div>
      </div>
      <button class="toast-close" aria-label="Close">✕</button>
      <div class="toast-progress"></div>
    `;

    container.appendChild(el);

    const close = () => {
      el.classList.add('removing');
      el.addEventListener('animationend', () => el.remove(), { once: true });
    };

    el.querySelector('.toast-close').addEventListener('click', close);
    setTimeout(close, duration);
    return el;
  }

  function createOverlay() {
    const overlay = document.createElement('div');
    overlay.className = 'ui-modal-overlay';
    document.body.appendChild(overlay);
    return overlay;
  }

  function closeOverlay(overlay) {
    overlay.classList.add('removing');
    overlay.addEventListener('animationend', () => overlay.remove(), { once: true });
  }

  function alert(message, type = 'info', title = '') {
    return new Promise(resolve => {
      const lang = getLang();
      const rtl = isRtl();
      const resolvedTitle = title || (TITLES[type] ? TITLES[type][lang] || TITLES[type].en : '');
      const overlay = createOverlay();

      const modal = document.createElement('div');
      modal.className = `ui-modal${rtl ? ' rtl' : ''}`;
      modal.innerHTML = `
        <div class="ui-modal-icon ${type}">${ICONS[type] || 'ℹ️'}</div>
        <div class="ui-modal-title">${resolvedTitle}</div>
        <div class="ui-modal-message">${message}</div>
        <div class="ui-modal-actions">
          <button class="ui-modal-btn ok ${type}">${BTN_OK[lang] || BTN_OK.en}</button>
        </div>
      `;
      overlay.appendChild(modal);

      modal.querySelector('.ui-modal-btn.ok').addEventListener('click', () => {
        closeOverlay(overlay);
        resolve(true);
      });
    });
  }

  function confirm(message, opts = {}) {
    return new Promise(resolve => {
      const lang = getLang();
      const rtl = isRtl();
      const type = opts.type || 'confirm';
      const title = opts.title || (TITLES[type][lang] || TITLES[type].en);
      const okLabel = opts.okLabel || (opts.danger ? (BTN_DEL[lang] || BTN_DEL.en) : (BTN_CONFIRM[lang] || BTN_CONFIRM.en));
      const cancelLabel = opts.cancelLabel || (BTN_CANCEL[lang] || BTN_CANCEL.en);
      const overlay = createOverlay();

      const modal = document.createElement('div');
      modal.className = `ui-modal${rtl ? ' rtl' : ''}`;
      modal.innerHTML = `
        <div class="ui-modal-icon ${type}">${opts.icon || ICONS[type] || '⚠️'}</div>
        <div class="ui-modal-title">${title}</div>
        <div class="ui-modal-message">${message}</div>
        <div class="ui-modal-actions">
          <button class="ui-modal-btn cancel">${cancelLabel}</button>
          <button class="ui-modal-btn confirm">${okLabel}</button>
        </div>
      `;
      overlay.appendChild(modal);

      modal.querySelector('.ui-modal-btn.cancel').addEventListener('click', () => {
        closeOverlay(overlay);
        resolve(false);
      });
      modal.querySelector('.ui-modal-btn.confirm').addEventListener('click', () => {
        closeOverlay(overlay);
        resolve(true);
      });

      overlay.addEventListener('click', e => {
        if (e.target === overlay) { closeOverlay(overlay); resolve(false); }
      });
    });
  }


  function prompt(message, defaultValue = '', opts = {}) {
    return new Promise(resolve => {
      const lang = getLang();
      const rtl = isRtl();
      const title = opts.title || (TITLES.info[lang] || TITLES.info.en);
      const overlay = createOverlay();

      const modal = document.createElement('div');
      modal.className = `ui-modal${rtl ? ' rtl' : ''}`;
      modal.innerHTML = `
        <div class="ui-modal-icon info">${opts.icon || ICONS.info}</div>
        <div class="ui-modal-title">${title}</div>
        <div class="ui-modal-message">${message}</div>
        <input class="ui-modal-input" type="text" value="${defaultValue || ''}" placeholder="${opts.placeholder || ''}" dir="${rtl ? 'rtl' : 'ltr'}">
        <div class="ui-modal-actions">
          <button class="ui-modal-btn cancel">${BTN_CANCEL[lang] || BTN_CANCEL.en}</button>
          <button class="ui-modal-btn ok">${BTN_SUBMIT[lang] || BTN_SUBMIT.en}</button>
        </div>
      `;
      overlay.appendChild(modal);

      const input = modal.querySelector('.ui-modal-input');
      input.focus();

      const submit = () => {
        const val = input.value.trim();
        closeOverlay(overlay);
        resolve(val || null);
      };

      modal.querySelector('.ui-modal-btn.ok').addEventListener('click', submit);
      modal.querySelector('.ui-modal-btn.cancel').addEventListener('click', () => {
        closeOverlay(overlay); resolve(null);
      });
      input.addEventListener('keydown', e => {
        if (e.key === 'Enter') submit();
        if (e.key === 'Escape') { closeOverlay(overlay); resolve(null); }
      });
    });
  }

  function multiPrompt(title, fields = [], opts = {}) {
    return new Promise(resolve => {
      const lang = getLang();
      const rtl = isRtl();
      const overlay = createOverlay();

      const fieldsHtml = fields.map(f => `
        <div style="margin-bottom:14px;">
          <label style="display:block;font-size:12px;color:#94a3b8;margin-bottom:6px;">${f.label || f.name}</label>
          <input class="ui-modal-input" style="margin-bottom:0"
            name="${f.name}" type="text"
            value="${f.defaultValue || ''}"
            placeholder="${f.placeholder || ''}"
            dir="${rtl ? 'rtl' : 'ltr'}"
            ${f.required ? 'required' : ''}>
        </div>
      `).join('');

      const modal = document.createElement('div');
      modal.className = `ui-modal${rtl ? ' rtl' : ''}`;
      modal.innerHTML = `
        <div class="ui-modal-icon info">${opts.icon || ICONS.info}</div>
        <div class="ui-modal-title">${title}</div>
        ${fieldsHtml}
        <div class="ui-modal-actions">
          <button class="ui-modal-btn cancel">${BTN_CANCEL[lang] || BTN_CANCEL.en}</button>
          <button class="ui-modal-btn ok">${BTN_SUBMIT[lang] || BTN_SUBMIT.en}</button>
        </div>
      `;
      overlay.appendChild(modal);

      const firstInput = modal.querySelector('.ui-modal-input');
      if (firstInput) firstInput.focus();

      const submit = () => {
        const result = {};
        modal.querySelectorAll('.ui-modal-input').forEach(inp => {
          result[inp.name] = inp.value.trim();
        });
        closeOverlay(overlay);
        resolve(result);
      };

      modal.querySelector('.ui-modal-btn.ok').addEventListener('click', submit);
      modal.querySelector('.ui-modal-btn.cancel').addEventListener('click', () => {
        closeOverlay(overlay); resolve(null);
      });
    });
  }

  return { toast, alert, confirm, prompt, multiPrompt };
})();

function togglePassword(btn) {
  const wrapper = btn.closest('.password-wrapper');
  const input = wrapper.querySelector('input');
  const eyeIcon = btn.querySelector('.eye-icon');
  const eyeOffIcon = btn.querySelector('.eye-off-icon');

  if (input.type === 'password') {
    input.type = 'text';
    eyeIcon.style.display = 'none';
    eyeOffIcon.style.display = 'block';
    btn.setAttribute('aria-label', 'Hide password');
  } else {
    input.type = 'password';
    eyeIcon.style.display = 'block';
    eyeOffIcon.style.display = 'none';
    btn.setAttribute('aria-label', 'Show password');
  }
}
