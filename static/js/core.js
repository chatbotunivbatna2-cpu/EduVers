const I18n = {
  current: localStorage.getItem("lang") || "en",

  t(key) {
    return (TRANSLATIONS[this.current] && TRANSLATIONS[this.current][key])
      || (TRANSLATIONS["en"] && TRANSLATIONS["en"][key])
      || key;
  },

  setLang(lang) {
    this.current = lang;
    localStorage.setItem("lang", lang);
    this.applyAll();
    window.dispatchEvent(new CustomEvent("langChanged", { detail: { lang } }));
  },

  applyAll() {
    const lang = this.current;
    const isAr = lang === "ar";

    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", isAr ? "rtl" : "ltr");
    document.body.classList.toggle("rtl", isAr);

    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const val = this.t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = val;
      } else if (el.tagName === "OPTION") {
        el.textContent = val;
      } else if (val.includes("<")) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
      el.placeholder = this.t(el.getAttribute("data-i18n-ph"));
    });

    document.querySelectorAll(".lang-btn").forEach(btn => {
      btn.classList.toggle("lang-btn--active", btn.getAttribute("data-lang") === lang);
    });
  },

  init() {
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", () => this.applyAll());
    } else {
      this.applyAll();
    }
  }
};

